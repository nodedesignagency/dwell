#!/usr/bin/env python3
"""Generate colour assets and Swift token constants from design/tokens.json.

Writes:
  Packages/DwellKit/Sources/DwellUI/Resources/Colors.xcassets   (owned by this script, rebuilt each run)
  Packages/DwellKit/Sources/DwellUI/Tokens/Tokens.generated.swift
  Dwell/Resources/Assets.xcassets/AccentColor.colorset           (from color.accent)

Run from anywhere: python3 scripts/tokens.py
"""

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
UI = ROOT / "Packages" / "DwellKit" / "Sources" / "DwellUI"
CATALOG = UI / "Resources" / "Colors.xcassets"
SWIFT = UI / "Tokens" / "Tokens.generated.swift"
ACCENT = ROOT / "Dwell" / "Resources" / "Assets.xcassets" / "AccentColor.colorset"

INFO = {"author": "xcode", "version": 1}
HEX = re.compile(r"^#([0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?$")


def component(hex_value):
    match = HEX.match(hex_value)
    if not match:
        raise SystemExit(f"Bad colour {hex_value!r}: use #RRGGBB or #RRGGBBAA")
    rgb, alpha = match.group(1), match.group(2) or "FF"
    return {
        "color-space": "srgb",
        "components": {
            "red": f"0x{rgb[0:2].upper()}",
            "green": f"0x{rgb[2:4].upper()}",
            "blue": f"0x{rgb[4:6].upper()}",
            "alpha": f"{int(alpha, 16) / 255:.3f}",
        },
    }


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + "\n")


def write_colorset(folder, token):
    write_json(folder / "Contents.json", {
        "colors": [
            {"color": component(token["light"]), "idiom": "universal"},
            {
                "appearances": [{"appearance": "luminosity", "value": "dark"}],
                "color": component(token["dark"]),
                "idiom": "universal",
            },
        ],
        "info": INFO,
    })


def camel(name):
    return name[0].lower() + name[1:]


def main():
    tokens = json.loads(TOKENS.read_text())

    if CATALOG.exists():
        shutil.rmtree(CATALOG)
    write_json(CATALOG / "Contents.json", {"info": INFO})
    for name, token in tokens["color"].items():
        write_colorset(CATALOG / f"{name}.colorset", token)
    write_json(CATALOG / "category" / "Contents.json", {"info": INFO, "properties": {"provides-namespace": True}})
    for name, token in tokens["category"].items():
        write_colorset(CATALOG / "category" / f"{name}.colorset", token)

    write_colorset(ACCENT, tokens["color"]["accent"])

    lines = [
        "// Generated by scripts/tokens.py from design/tokens.json. Edit the JSON, not this file.",
        "",
        "import DwellCore",
        "import SwiftUI",
        "",
        "public enum Palette {",
    ]
    for name, token in tokens["color"].items():
        note = " (placeholder)" if token.get("placeholder") else ""
        lines.append(f"    /// {token.get('use', name)}{note}")
        lines.append(f'    public static let {camel(name)} = Color("{name}", bundle: .module)')
    lines += [
        "}",
        "",
        "extension PlaceCategory {",
        "    /// Never the only carrier of identity: pair it with the category's icon or name.",
        "    public var color: Color {",
        '        Color("category/\\(rawValue)", bundle: .module)',
        "    }",
        "}",
        "",
        "/// Plain numbers, so nonisolated: usable in layouts and default arguments.",
        "public nonisolated enum Space {",
    ]
    for name, value in tokens["space"].items():
        lines.append(f"    public static let {name}: CGFloat = {value}")
    lines += ["}", "", "public nonisolated enum Radius {"]
    for name, value in tokens["radius"].items():
        lines.append(f"    public static let {name}: CGFloat = {value}")
    lines += ["}", ""]
    SWIFT.parent.mkdir(parents=True, exist_ok=True)
    SWIFT.write_text("\n".join(lines))

    print(f"{len(tokens['color'])} colours, {len(tokens['category'])} categories, "
          f"{len(tokens['space'])} spaces, {len(tokens['radius'])} radii")


if __name__ == "__main__":
    main()
